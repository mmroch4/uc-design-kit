#!/usr/bin/env node
/**
 * Builds kit/v1/uc-kit.js and kit/v1/uc-kit.css by concatenating the files
 * listed in kit/src/manifest.json. No transpilation, no minification: the
 * output is readable and identical in behaviour to the sources.
 *
 * Usage: node scripts/build.mjs [--check]
 *   --check  exits with an error when kit/v1 is out of date (used in CI).
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "kit", "src");
const OUT = path.join(ROOT, "kit", "v1");

async function bundle(files, kind) {
  const pkg = JSON.parse(await readFile(path.join(ROOT, "package.json"), "utf8"));
  const header = `/*! UC Design Kit ${pkg.version} | MIT License | https://github.com/mmroch4/uc-design-kit\n * Generated by scripts/build.mjs from kit/src. Do not edit by hand. */\n`;
  const parts = await Promise.all(
    files.map(async (file) => {
      const content = (await readFile(path.join(SRC, file), "utf8")).trimEnd();
      return `/* --- ${file} --- */\n${content}\n`;
    }),
  );
  // CSS @import rules must come before any other rule.
  if (kind === "css") {
    const imports = [];
    const rest = parts.map((part) =>
      part.replace(/^@import[^;]+;\s*$/gm, (rule) => {
        imports.push(rule);
        return "";
      }),
    );
    return `${imports.join("\n")}\n${header}\n${rest.join("\n")}`;
  }
  return `${header}\n${parts.join("\n")}`;
}

async function main() {
  const check = process.argv.includes("--check");
  const manifest = JSON.parse(await readFile(path.join(SRC, "manifest.json"), "utf8"));
  const outputs = {
    "uc-kit.js": await bundle(manifest.js, "js"),
    "uc-kit.css": await bundle(manifest.css, "css"),
  };
  await mkdir(OUT, { recursive: true });
  let stale = false;
  for (const [name, content] of Object.entries(outputs)) {
    const target = path.join(OUT, name);
    const previous = await readFile(target, "utf8").catch(() => "");
    if (previous === content) continue;
    if (check) {
      console.error(`kit/v1/${name} is out of date. Run: npm run build`);
      stale = true;
    } else {
      await writeFile(target, content);
      console.log(`wrote kit/v1/${name} (${(content.length / 1024).toFixed(1)} KB)`);
    }
  }
  if (stale) process.exitCode = 1;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
