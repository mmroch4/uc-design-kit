class IndexFileTest(SiteTestCase):
    def setUp(self):
        super().setUp()
        self.write("course.js", SEARCH_ON)
        os.environ["SOURCE_DATE_EPOCH"] = "1795000000"
        self.addCleanup(os.environ.pop, "SOURCE_DATE_EPOCH", None)

    def read_index(self, name="search-index.js"):
        with open(os.path.join(self.dir, name), encoding="utf-8") as f:
            return f.read()

    def test_written_by_the_default_command(self):
        code, output = self.run_script("--lang", "pt")
        self.assertEqual(code, 0, output)
        self.assertEqual(output.splitlines()[-1], "Índice: search-index.js (2 páginas, 2 secções, 1 KB)")
        source = self.read_index()
        self.assertTrue(source.startswith("/* Generated by uc-site.py {}. Do not edit".format(uc_site.VERSION)))
        index = parse_index(source)
        self.assertEqual(
            {k: v for k, v in index.items() if k != "pages"},
            {"v": 1, "generator": "uc-site.py " + uc_site.VERSION, "generated": "2026-11-18T11:06:40Z", "course": "CC0000", "languages": ["pt"]},
        )
        self.assertEqual([p["p"] for p in index["pages"]], ["index.html", "semanas.html"])
        self.assertEqual(index["pages"][1]["s"], [{"i": "semana-1", "h": "Semana 1", "x": "", "w": "semana 1"}])
        # One page per line, so that diffs stay readable.
        self.assertEqual(len(source.splitlines()), 2 + len(index["pages"]) + 1)
        self.assertEqual(stat.S_IMODE(os.stat(os.path.join(self.dir, "search-index.js")).st_mode), 0o644)
        self.assertNotIn("search-index.js.tmp", os.listdir(self.dir))

    def test_english_summary(self):
        _, output = self.run_script("index", "--lang", "en")
        self.assertEqual(output.splitlines()[-1], "Index: search-index.js (2 pages, 2 sections, 1 KB)")

    def test_index_command_skips_the_checks(self):
        self.write("index.html", page('<h1>Início</h1>\n<a href="x.html">x</a>'))
        code, output = self.run_script("index", "--lang", "en")
        self.assertEqual(code, 0)
        self.assertNotIn("x.html", output)
        self.assertIn("Index: search-index.js", output)

    def test_errors_do_not_block_the_index(self):
        self.write("index.html", page('<h1>Início</h1>\n<a href="x.html">x</a>'))
        code, output = self.run_script("--lang", "en")
        self.assertEqual(code, 1)
        self.assertIn("link to x.html", output)
        self.assertTrue(os.path.isfile(os.path.join(self.dir, "search-index.js")))

    def test_quiet(self):
        code, output = self.run_script("--quiet")
        self.assertEqual((code, output), (0, ""))
        self.assertTrue(os.path.isfile(os.path.join(self.dir, "search-index.js")))

    def test_stdout(self):
        out = io.StringIO()
        code = uc_site.main(["index", "--stdout", "--site", self.dir], out=out, default_site=self.dir)
        self.assertEqual(code, 0)
        self.assertEqual(parse_index(out.getvalue())["course"], "CC0000")
        self.assertFalse(os.path.exists(os.path.join(self.dir, "search-index.js")))
        stderr = sys.stderr
        sys.stderr = io.StringIO()
        try:
            self.assertEqual(uc_site.main(["--stdout", "--site", self.dir], out=io.StringIO()), 2)
        finally:
            sys.stderr = stderr

    def test_reproducible(self):
        self.run_script("index")
        first = self.read_index()
        self.run_script("index")
        self.assertEqual(self.read_index(), first)

    def test_options_index_and_exclude(self):
        self.write("course.js", COURSE.replace("updated:", 'search: { index: "dados/indice.js", exclude: ["rascunhos/", "velho.html"] },\n  updated:'))
        self.write("rascunhos/a.html", page("<h1>A</h1>", depth=1))
        self.write("velho.html", page("<h1>Velho</h1>"))
        self.write("_privado/b.html", page("<h1>B</h1>", depth=1))
        self.write("aulas/c.html", page("<h1>C</h1><p>texto</p>", depth=1))
        self.run_script("index")
        index = parse_index(self.read_index("dados/indice.js"))
        self.assertEqual([p["p"] for p in index["pages"]], ["aulas/c.html", "index.html", "semanas.html"])

    def test_index_outside_the_site(self):
        self.write("course.js", COURSE.replace("updated:", 'search: { index: "../fora.js" },\n  updated:'))
        code, output = self.run_script("index", "--lang", "en", "--quiet")
        self.assertEqual(code, 1)
        self.assertIn("must be inside the site folder", output)

    def test_write_failure(self):
        if hasattr(os, "geteuid") and os.geteuid() == 0:
            self.skipTest("root can write anywhere")
        os.chmod(self.dir, 0o555)
        self.addCleanup(os.chmod, self.dir, 0o755)
        code, output = self.run_script("index", "--lang", "en", "--quiet")
        self.assertEqual(code, 1)
        self.assertIn("Index: could not write search-index.js", output)

    def test_bilingual_site(self):
        self.write("course.js", BILINGUAL.replace('{ id: "weeks", href: "semanas.html" }', '{ id: "weeks", href: { pt: "semanas.html", en: "weeks.html" } }'))
        self.write("weeks.html", page("<h1>Weeks</h1><h2>Week 1</h2>"))
        self.write("index.html", page('<h1>Início</h1><p lang="pt"><a href="semanas.html">Semanas</a></p><p lang="en"><a href="weeks.html">Weeks</a></p>'))
        self.run_script("index")
        index = parse_index(self.read_index())
        self.assertEqual(index["languages"], ["pt", "en"])
        self.assertEqual([(p["p"], p.get("l")) for p in index["pages"]], [("index.html", "pt"), ("index.html", "en"), ("semanas.html", "pt"), ("weeks.html", "en")])


