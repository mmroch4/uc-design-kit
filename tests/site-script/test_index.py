class SharedCasesTest(unittest.TestCase):
    def test_slugs(self):
        for case in load_json("slugs.json"):
            with self.subTest(case["about"]):
                languages = case.get("languages", [])
                indexer = uc_site.PageIndexer(languages)
                indexer.feed(page(case["html"]))
                indexer.close()
                uc_site.assign_ids(indexer, languages[0] if len(languages) > 1 else None)
                ids = [s.id for s in indexer.sections if s.kind in ("h2", "h3")]
                self.assertEqual(ids, case["ids"])

    def test_words(self):
        shared = load_json("words.json")
        self.assertEqual(sorted(uc_site.STOP_WORDS), shared["stopWords"])
        for case in shared["cases"]:
            with self.subTest(case["about"]):
                self.assertEqual(uc_site.search_words(case["text"]), case["words"])

    def test_slugify_and_fold(self):
        self.assertEqual(uc_site.fold("Secção ÁRVORE"), "seccao arvore")
        self.assertEqual(uc_site.slugify("  Árvores AVL (rotações)  "), "arvores-avl-rotacoes")
        self.assertEqual(uc_site.slugify("—"), "section")


class ExcerptTest(unittest.TestCase):
    def test_short_text_unchanged(self):
        self.assertEqual(uc_site.excerpt("Uma frase curta."), "Uma frase curta.")

    def test_cut_at_a_space_without_trailing_punctuation(self):
        text = ("palavra " * 17) + "fim, mais texto depois do corte"
        result = uc_site.excerpt(text)
        self.assertTrue(result.endswith("…"))
        self.assertLessEqual(len(result), 141)
        self.assertNotIn(",…", result)
        self.assertFalse(result[:-1].endswith(" "))

    def test_long_word(self):
        self.assertEqual(uc_site.excerpt("x" * 200), "x" * 140 + "…")


