SHARED = os.path.join(ROOT, "tests", "search")
SEARCH_ON = COURSE.replace("updated:", "search: true,\n  updated:")
BILINGUAL = SEARCH_ON.replace('languages: ["pt"]', 'languages: ["pt", "en"]')


def load_json(name):
    with open(os.path.join(SHARED, name), encoding="utf-8") as f:
        return json.load(f)


def parse_index(source):
    """The object of a search-index.js file."""
    match = re.match(r"\A/\* Generated by [^*]+\*/\nwindow\.UC_SEARCH_INDEX = (.*);\n\Z", source, re.S)
    if not match:
        raise AssertionError("not an index file:\n" + source[:300])
    return json.loads(match.group(1))


def index_of_html(body, languages=(), file_lang=None, rel="p.html", wrap=True):
    """The entries of one page made of `body`."""
    indexer = uc_site.PageIndexer(list(languages))
    indexer.feed(page(body) if wrap else body)
    indexer.close()
    return uc_site.page_entries(indexer, rel, list(languages), file_lang)


