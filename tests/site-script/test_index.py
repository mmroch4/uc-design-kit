class SectionsTest(unittest.TestCase):
    def sections(self, body, **options):
        entries = index_of_html(body, **options)
        self.assertEqual(len(entries), 1)
        return entries[0]["s"]

    def test_intro_and_headings(self):
        s = self.sections("<h1>Aula</h1><p>Intro.</p><h2 id='a'>Um</h2><p>Texto um.</p><h3>Dois</h3><p>Texto dois.</p><h4>Quatro</h4><p>mais</p>")
        self.assertEqual([(x["i"], x["h"], x["x"]) for x in s], [("", "", "Intro."), ("a", "Um", "Texto um."), ("dois", "Dois", "Texto dois. Quatro mais")])
        self.assertEqual(s[1]["w"], "texto")

    def test_intro_left_out_when_empty(self):
        s = self.sections("<h1>Aula</h1><h2 id='a'>Um</h2><p>x</p>")
        self.assertEqual([x["i"] for x in s], ["a"])

    def test_page_title(self):
        entry = index_of_html("<h1>Aula <em>5</em></h1>")[0]
        self.assertEqual(entry["t"], "Aula 5")
        entry = index_of_html("<uc-hero></uc-hero><p>x</p>")[0]
        self.assertEqual(entry["t"], "Página")  # <title>Página</title>
        indexer = uc_site.PageIndexer([])
        indexer.feed("<html><head><title>Semanas · Estruturas de Dados</title></head><body><p>x</p></body></html>")
        indexer.close()
        self.assertEqual(uc_site.page_entries(indexer, "s.html", [], None)[0]["t"], "Semanas")

    def test_group(self):
        source = page("<h1>S</h1>").replace("<uc-page>", '<uc-page current="weeks">')
        indexer = uc_site.PageIndexer([])
        indexer.feed(source)
        indexer.close()
        entry = uc_site.page_entries(indexer, "s.html", [], None)[0]
        self.assertEqual(entry["g"], "weeks")
        self.assertNotIn("g", index_of_html("<h1>S</h1>")[0])

    def test_items(self):
        s = self.sections(
            '<h1>P</h1>'
            '<uc-week n="3" title="Listas"><p>Texto da semana.</p><h3>Leituras</h3><p>Capítulo 4.</p></uc-week>'
            '<p>Depois da semana.</p>'
            '<uc-exercise id="ex1" title="Somar"><p>Some dois números.</p></uc-exercise>'
            '<uc-question id="q1"><p>Pergunta?</p></uc-question>'
            '<ul><li id="p001"><a href="p001.html">Problema 1</a> fácil</li><li>sem id</li></ul>'
            '<article id="n1"><h4>Nota</h4><p>Texto da nota.</p></article>'
            '<li id="t" data-search-title="Outro título"><a href="x.html">Link</a></li>'
        )
        got = [(x["i"], x["h"], x["x"]) for x in s]
        self.assertEqual(
            got,
            [
                ("", "", "Depois da semana. sem id"),
                ("week-3", "Listas", "Texto da semana."),
                ("leituras", "Leituras", "Capítulo 4."),
                ("ex1", "Somar", "Some dois números."),
                ("q1", "", "Pergunta?"),
                ("p001", "Problema 1", "fácil"),
                ("n1", "Nota", "Texto da nota."),
                ("t", "Outro título", "Link"),
            ],
        )

    def test_data_search_title_on_heading(self):
        s = self.sections('<h1>P</h1><h2 id="a" data-search-title="Curto">Um título muito longo</h2><p>x</p>')
        self.assertEqual(s[0]["h"], "Curto")
        self.assertIn("curto", s[0]["w"])

    def test_text_left_out(self):
        s = self.sections(
            "<h1>P</h1><h2 id='a'>A</h2><p>visível</p>"
            "<script>secreto1()</script><style>.secreto2{}</style><noscript>secreto3</noscript>"
            "<template><p>secreto4</p></template><nav>secreto5</nav><svg><text>secreto6</text></svg>"
            "<div data-search-ignore><p>secreto7</p><h2>Escondido</h2></div>"
            '<uc-code filename="Main.java">secreto8 class Main {}</uc-code>'
            '<img src="a.png" alt="diagrama da pilha"><img src="b.png" alt="">'
        )
        self.assertEqual(len(s), 1)
        self.assertEqual(s[0]["x"], "visível Main.java diagrama da pilha")
        self.assertNotIn("secreto", json.dumps(s))
        self.assertNotIn("escondido", s[0]["w"])

    def test_ignored_heading_keeps_numbering(self):
        s = self.sections("<h1>P</h1><div data-search-ignore><h2>A</h2></div><h2>A</h2><p>x</p>")
        self.assertEqual([x["i"] for x in s], ["a-2"])

    def test_noindex(self):
        source = page("<h1>P</h1><p>x</p>").replace("<uc-page>", '<uc-page search="noindex">')
        indexer = uc_site.PageIndexer([])
        indexer.feed(source)
        indexer.close()
        self.assertEqual(uc_site.page_entries(indexer, "p.html", [], None), [])

    def test_page_without_uc_page(self):
        # An old page copied as it was: the kit gives its headings no id, so the result links to the page.
        entries = index_of_html("<html><body><h1>Velho</h1><h2>Parte</h2><p>texto</p></body></html>", wrap=False)
        self.assertEqual(entries[0]["s"], [{"i": "", "h": "Parte", "x": "texto", "w": "parte texto"}])

    def test_unclosed_elements(self):
        s = self.sections("<h1>P</h1><h2 id='a'>A</h2><ul><li>um<li>dois</ul><p>três<p>quatro")
        self.assertEqual(s[0]["x"], "um dois três quatro")


class LanguagesTest(unittest.TestCase):
    def test_single_language_has_no_l(self):
        entries = index_of_html("<h1>P</h1><p>x</p>", languages=["pt"])
        self.assertEqual(len(entries), 1)
        self.assertNotIn("l", entries[0])

    def test_bilingual_page_without_language_text(self):
        entries = index_of_html("<h1>Mooshak</h1><p>x</p>", languages=["pt", "en"])
        self.assertEqual(len(entries), 1)
        self.assertNotIn("l", entries[0])

    def test_one_entry_per_language(self):
        body = (
            '<h1><span lang="pt">Avaliação</span><span lang="en">Assessment</span></h1>'
            '<h2><span lang="pt">Fórmula</span><span lang="en">Formula</span></h2>'
            '<p>Comum: 50%.</p><p lang="pt">Texto em português.</p><p lang="en-GB">English text.</p>'
            '<uc-week n="1" title="Introdução" title-en="Introduction"></uc-week>'
        )
        pt, en = index_of_html(body, languages=["pt", "en"])
        self.assertEqual((pt["l"], pt["t"]), ("pt", "Avaliação"))
        self.assertEqual((en["l"], en["t"]), ("en", "Assessment"))
        # The automatic id comes from the first language in both entries.
        self.assertEqual([(x["i"], x["h"], x["x"]) for x in pt["s"]], [("formula", "Fórmula", "Comum: 50%. Texto em português."), ("week-1", "Introdução", "")])
        self.assertEqual([(x["i"], x["h"], x["x"]) for x in en["s"]], [("formula", "Formula", "Comum: 50%. English text."), ("week-1", "Introduction", "")])

    def test_week_title_in_another_language_makes_entries(self):
        entries = index_of_html('<h1>S</h1><uc-week n="1" title="Introdução" title-en="Introduction"></uc-week>', languages=["pt", "en"])
        self.assertEqual([e["l"] for e in entries], ["pt", "en"])

    def test_html_lang_is_not_language_text(self):
        source = page("<h1>Materiais</h1><p>x</p>").replace('lang="pt"', 'lang="pt"')
        self.assertIn('<html lang="pt">', source)
        indexer = uc_site.PageIndexer(["pt", "en"])
        indexer.feed(source)
        indexer.close()
        self.assertEqual(len(uc_site.page_entries(indexer, "m.html", ["pt", "en"], None)), 1)

    def test_keep_lang(self):
        entries = index_of_html('<h1>P</h1><p lang="en" data-uc-keep-lang>Always shown</p>', languages=["pt", "en"])
        self.assertEqual(len(entries), 1)

    def test_whole_language_file(self):
        body = '<h1>About</h1><h2>Goals</h2><p>Common.</p><p lang="pt">Só em português.</p>'
        entries = index_of_html(body, languages=["pt", "en"], file_lang="en")
        self.assertEqual(len(entries), 1)
        self.assertEqual(entries[0]["l"], "en")
        self.assertEqual([(x["i"], x["x"]) for x in entries[0]["s"]], [("goals", "Common.")])


